# units.py
# Контракт единиц для Bio-COMSOL (Ступень 1, v1.0).
# Все внутренние расчёты — строго в СИ (В, м, с, К).
# Все внешние входы/выходы (графики, UI) — в биологических (мВ, мкм, мс).
#
# ВАЖНО: обратное преобразование мВ -> В -> мВ не гарантирует бит-в-бит
# совпадения из-за арифметики с плавающей точкой (расхождение ~1e-14 мВ
# возможно примерно на 13% значений). Поэтому в тестах используйте
# pytest.approx, а не точное сравнение ==. Не удаляйте эту оговорку.

# Вольты <-> милливольты
MV_TO_V = 1e-3
V_TO_MV = 1e3

# Метры <-> микрометры (пригодится для моста с плазмой)
UM_TO_M = 1e-6
M_TO_UM = 1e6

# Фундаментальные константы (CODATA, округлено до рабочего значения)
FARADAY = 96485.33212     # Кл/моль
GAS_R = 8.314462618       # Дж/(моль*К)

# Температура тела
T_BODY = 310.15           # К (37 C)

# Рабочие связки (вычисляются из констант, не зашиты числом)
RT_F = GAS_R * T_BODY / FARADAY          # В; при 37 C = 26.7267 мВ
F_RT = 1.0 / RT_F                        # 1/В; при 37 C = 37.4158 1/В


def mv_to_v(val_mv: float) -> float:
    """Милливольты (биология) -> вольты (физика)."""
    return val_mv * MV_TO_V


def v_to_mv(val_v: float) -> float:
    """Вольты (физика) -> милливольты (биология)."""
    return val_v * V_TO_MV
